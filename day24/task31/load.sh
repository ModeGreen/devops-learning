#!/bin/bash
# Нагрузка на процессор для Задачи 31.
# На каждом логическом процессоре запускается программа yes: она печатает «y»
# без остановки, а вывод уходит в /dev/null — получается чистая работа для процессора.
#
# Запуск:  bash load.sh          — 120 секунд
#          bash load.sh 60       — 60 секунд
# Сама останавливается через заданное время. Остановить раньше — Ctrl+C.
# nice -n 19 — самый низкий приоритет: Navidrome и Syncthing получают процессор первыми.
# timeout — страховка: даже если окно закроется, yes остановятся сами.

seconds="${1:-120}"   # первый аргумент, а если его нет — 120
cores=$(nproc)
pids=""               # сюда собираются PID запущенных процессов

# Уборка: при любом выходе из скрипта (конец, Ctrl+C, закрытое окно)
# остановить все запущенные yes. trap — «когда случится X, выполни команду».
stop_load() {
    if [ -n "$pids" ]; then
        kill $pids 2>/dev/null
        pids=""
    fi
}
trap stop_load EXIT
trap 'echo; echo "Остановлено раньше времени."; exit 130' INT TERM HUP

# & — запустить в фоне и сразу идти дальше; $! — PID того, что только что запустили.
for i in $(seq "$cores"); do
    nice -n 19 timeout "$seconds" yes > /dev/null &
    pids="$pids $!"
done
echo "Запущено процессов yes: $cores (по одному на процессор), на $seconds с."
echo "Смотри load и температуру во втором окне. Остановить раньше — Ctrl+C."

left=$seconds
while [ "$left" -gt 0 ]; do
    echo "  осталось $left с"
    step=10
    if [ "$left" -lt 10 ]; then step=$left; fi
    sleep "$step"
    left=$((left - step))
done
wait        # дождаться, пока фоновые процессы закончатся
pids=""
echo "Нагрузка снята. Проверь: pgrep -x yes — пусто."
